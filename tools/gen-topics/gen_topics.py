#!/usr/bin/env python3
"""Генерирует deploy/compose/kafka/topics.txt из contracts/asyncapi/kafka-events.yaml.

Формат строки: имя|партиции|config1,config2. Для каждого топика создаётся <topic>.dlq
(1 партиция, retention 14 дней). Источник правды — AsyncAPI (bindings.kafka + x-dlq).
Режим --check завершает работу с ошибкой, если файл устарел (для CI).
"""
import sys, pathlib, yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "contracts/asyncapi/kafka-events.yaml"
DST = ROOT / "deploy/compose/kafka/topics.txt"

def build() -> str:
    doc = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    rows, dlq = [], []
    for name, ch in doc["channels"].items():
        kb = (ch.get("bindings") or {}).get("kafka")
        if not kb:
            continue  # вебхуки/пуши — не Kafka
        cfg = []
        for k, v in (kb.get("topicConfiguration") or {}).items():
            cfg.append("%s=%s" % (k, ",".join(v) if isinstance(v, list) else v))
        rows.append("%s|%d|%s" % (ch["address"], kb["partitions"], ",".join(cfg)))
        if ch.get("x-dlq"):
            dlq.append("%s|1|retention.ms=1209600000" % ch["x-dlq"])
    return "# GENERATED by tools/gen-topics/gen_topics.py from contracts/asyncapi — не править руками (make topics)\n" \
           "# имя|партиции|config\n" + "\n".join(sorted(rows) + sorted(dlq)) + "\n"

if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text(encoding="utf-8") != text:
            sys.exit("topics.txt is stale: run `make topics`")
        print("topics.txt is up to date")
    else:
        DST.write_text(text, encoding="utf-8")
        print("written", DST.relative_to(ROOT))
